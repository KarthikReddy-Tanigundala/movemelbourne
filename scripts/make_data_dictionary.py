"""Generate DATA_DICTIONARY.md from dbt's manifest (descriptions) and catalog (types).

    uv run python scripts/run_pipeline.py --sample --docs   # produces dbt/target/*.json
    uv run python scripts/make_data_dictionary.py

The dictionary is generated, never hand-edited, so it cannot drift from the schema YAML.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TARGET = REPO_ROOT / "dbt" / "target"
OUT = REPO_ROOT / "DATA_DICTIONARY.md"
ORDER = ("dim_", "fact_", "agg_", "audit_")


def main() -> int:
    manifest = json.loads((TARGET / "manifest.json").read_text(encoding="utf-8"))
    catalog = json.loads((TARGET / "catalog.json").read_text(encoding="utf-8"))
    marts = [
        n
        for n in manifest["nodes"].values()
        if n["resource_type"] == "model" and n["schema"] == "marts"
    ]
    marts.sort(
        key=lambda n: (next(i for i, p in enumerate(ORDER) if n["name"].startswith(p)), n["name"])
    )
    lines = [
        "# Data dictionary",
        "",
        "Generated by `scripts/make_data_dictionary.py` from the dbt manifest and catalog. "
        "Schema `marts` in the DuckDB warehouse; the same tables are exported to `powerbi/data` "
        "and (aggregated) to `app/data`. Lineage: the dbt docs site.",
        "",
        "Contents: " + " · ".join(f"[{n['name']}](#{n['name']})" for n in marts),
        "",
    ]
    for node in marts:
        cat_cols = catalog["nodes"].get(node["unique_id"], {}).get("columns", {})
        lines += [
            f"## {node['name']}",
            "",
            node.get("description", "").strip(),
            "",
            "| Column | Type | Description |",
            "|---|---|---|",
        ]
        documented = node.get("columns", {})
        names = list(documented) + [c for c in cat_cols if c not in documented]
        for col in names:
            ctype = cat_cols.get(col, {}).get("type", "")
            desc = (
                documented.get(col, {})
                .get("description", "")
                .replace("\n", " ")
                .replace("|", "\\|")
            )
            lines.append(f"| `{col}` | {ctype} | {desc or '_(undocumented)_'} |")
        lines.append("")
    lines += [
        "## Glossary",
        "",
        "| Term | Meaning |",
        "|---|---|",
        "| Proxy OTP | MoveMelbourne's on-time performance at every observed stop (not the official measure; ADR-007) |",
        "| Coverage | Observed ÷ collectable scheduled stop events |",
        "| Reliability | 1 − confirmed cancelled ÷ scheduled trips fully inside collected time |",
        "| Service date | GTFS operating day; after-midnight trips belong to the previous date |",
        "| feed_version | Timetable release id: download date + SHA-256 prefix (ADR-005) |",
        "| Collection session | Collector runs less than 1 h apart; gaps inside count against coverage |",
        "| Last prediction | Primary observed-arrival method (ADR-004) |",
        "| Headway | Time between consecutive vehicles at a stop |",
        "| Bunching | Actual headway < 0.5 × scheduled |",
        "| Excess wait | Extra average wait vs timetable for a randomly arriving passenger |",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    undocumented = sum(line.endswith("_(undocumented)_ |") for line in lines)
    print(f"wrote {OUT} ({len(marts)} models, {undocumented} undocumented columns)")
    return 1 if undocumented else 0


if __name__ == "__main__":
    sys.exit(main())
