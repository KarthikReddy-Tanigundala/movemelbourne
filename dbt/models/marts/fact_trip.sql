-- Grain: service_date x mode x scheduled trip. Feeds reliability (service delivery).
select
    md5(mode || '|' || service_date || '|' || trip_id) as trip_event_key,
    cast(strftime(service_date, '%Y%m%d') as integer) as date_key,
    service_date,
    mode,
    md5(mode || '|' || route_id) as route_key,
    md5(mode || '|' || trip_id) as trip_key,
    feed_version,
    trip_id,
    direction_id,
    trip_headsign,
    hour({{ local_ts('first_departure_epoch') }}) as time_band_key,
    first_departure_epoch,
    {{ local_ts('first_departure_epoch') }} as first_departure_local,
    last_arrival_epoch,
    n_stops,
    n_collected_stops,
    n_observed_stops,
    origin_delay_s,
    destination_delay_s,
    max_delay_s,
    in_feed,
    is_canceled,
    n_polls,
    is_reliability_eligible,
    trip_outcome,
    trip_outcome = 'cancelled' as is_confirmed_cancelled,
    trip_outcome = 'no_data' as is_no_data
from {{ ref('int_trip_outcomes') }}
