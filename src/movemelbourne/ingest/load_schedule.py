"""Derive the service calendar for every timetable version in the lake (CLAUDE.md §7).

For each ``feed_version`` x ``mode_branch`` this expands ``calendar`` + ``calendar_dates`` into
one row per (service_date, service_id) that actually runs, and attaches ``ref_epoch``: the GTFS
"noon minus 12h" reference instant for that service date in Melbourne time. dbt then computes
every scheduled stop instant as ``ref_epoch + arrival_secs``, which is DST-correct and handles
times past 24:00 without any clock-time parsing in SQL.

It also writes ``docs/schedule_validation.md``: required files present, referential integrity of
stop_times -> trips/stops, parent-station coverage, and calendar validity per version.

    uv run python -m movemelbourne.ingest.load_schedule
"""

from __future__ import annotations

import argparse
import logging
import sys
from datetime import date, timedelta
from pathlib import Path

import duckdb
import pyarrow as pa
import pyarrow.parquet as pq

from movemelbourne import config
from movemelbourne.ingest.static_snapshot import REQUIRED_TABLES
from movemelbourne.utils.lake import lake_dir
from movemelbourne.utils.logging import setup_logging
from movemelbourne.utils.timeutil import parse_service_date, service_day_reference_epoch

logger = logging.getLogger("movemelbourne.schedule")

WEEKDAYS = ("monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday")
SERVICE_CALENDAR_SCHEMA = pa.schema(
    [
        ("feed_version", pa.string()),
        ("mode_branch", pa.string()),
        ("service_date", pa.date32()),
        ("service_id", pa.string()),
        ("ref_epoch", pa.int64()),
    ]
)


def expand_calendar(
    calendar: list[dict], calendar_dates: list[dict]
) -> dict[tuple[date, str], bool]:
    """Apply GTFS calendar rules. Returns {(service_date, service_id): runs}."""
    active: dict[tuple[date, str], bool] = {}
    for row in calendar:
        start, end = parse_service_date(row["start_date"]), parse_service_date(row["end_date"])
        d = start
        while d <= end:
            if row[WEEKDAYS[d.weekday()]] == "1":
                active[(d, row["service_id"])] = True
            d += timedelta(days=1)
    for row in calendar_dates:
        key = (parse_service_date(row["date"]), row["service_id"])
        if row["exception_type"] == "1":
            active[key] = True
        elif row["exception_type"] == "2":
            active[key] = False
    return active


def version_branches(lake: Path) -> list[tuple[str, str, Path]]:
    """(feed_version, mode_branch, folder) for every converted timetable in the lake."""
    out = []
    for folder in sorted((lake / "raw" / "schedule").glob("feed_version=*/mode_branch=*")):
        out.append((folder.parent.name.split("=", 1)[1], folder.name.split("=", 1)[1], folder))
    return out


def build_service_calendar(lake: Path) -> pa.Table:
    """Service calendar rows for every version x branch in the lake."""
    rows: list[dict] = []
    ref_cache: dict[date, int] = {}
    for feed_version, branch, folder in version_branches(lake):
        calendar = pq.read_table(folder / "calendar.parquet").to_pylist()
        cd_path = folder / "calendar_dates.parquet"
        calendar_dates = pq.read_table(cd_path).to_pylist() if cd_path.exists() else []
        for (d, service_id), runs in sorted(expand_calendar(calendar, calendar_dates).items()):
            if not runs:
                continue
            if d not in ref_cache:
                ref_cache[d] = service_day_reference_epoch(d)
            rows.append(
                {
                    "feed_version": feed_version,
                    "mode_branch": branch,
                    "service_date": d,
                    "service_id": service_id,
                    "ref_epoch": ref_cache[d],
                }
            )
    return pa.Table.from_pylist(rows, schema=SERVICE_CALENDAR_SCHEMA)


def validate(lake: Path) -> list[str]:
    """Markdown lines describing integrity checks for each version x branch."""
    con = duckdb.connect()
    lines = [
        "# Static schedule validation",
        "",
        "Generated by `movemelbourne.ingest.load_schedule`. One row per timetable version and "
        "mode branch.",
        "",
        "| feed_version | branch | missing files | trips | stop_times | orphan stop_times (trip) "
        "| orphan stop_times (stop) | platforms with parent | shapes loadable |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for feed_version, branch, folder in version_branches(lake):
        present = {p.stem for p in folder.glob("*.parquet")}
        missing = [t for t in REQUIRED_TABLES if t not in present] or "none"
        f = {t: (folder / f"{t}.parquet").as_posix() for t in present}
        q = con.sql(f"""
            select
              (select count(*) from '{f["trips"]}') as trips,
              (select count(*) from '{f["stop_times"]}') as stop_times,
              (select count(*) from '{f["stop_times"]}' st
                 where not exists (select 1 from '{f["trips"]}' t where t.trip_id = st.trip_id)) as orphan_trip,
              (select count(*) from '{f["stop_times"]}' st
                 where not exists (select 1 from '{f["stops"]}' s where s.stop_id = st.stop_id)) as orphan_stop,
              (select round(100.0 * count(*) filter (where parent_station <> '') / count(*), 1)
                 from '{f["stops"]}') as pct_parent
        """).fetchone()
        shapes_ok = "n/a"
        if "shapes" in f:
            bad = con.sql(f"""select count(*) from '{f["shapes"]}'
                where try_cast(shape_pt_lat as double) is null
                   or try_cast(shape_pt_lon as double) is null""").fetchone()[0]
            shapes_ok = "yes" if bad == 0 else f"{bad} bad points"
        lines.append(
            f"| {feed_version} | {branch} | {missing} | {q[0]:,} | {q[1]:,} | {q[2]:,} "
            f"| {q[3]:,} | {q[4]}% | {shapes_ok} |"
        )
    return lines


def main(argv: list[str] | None = None) -> int:
    setup_logging()
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--no-report", action="store_true", help="skip docs/schedule_validation.md")
    args = parser.parse_args(argv)
    lake = lake_dir()
    if not version_branches(lake):
        logger.error("no timetable versions under %s; run static_snapshot first", lake)
        return 1
    table = build_service_calendar(lake)
    dest = config.DATA_DIR / "derived" / "service_calendar.parquet"
    dest.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(table, dest, compression="zstd")
    logger.info("service calendar: %s rows -> %s", f"{table.num_rows:,}", dest)
    if not args.no_report:
        report = config.REPO_ROOT / "docs" / "schedule_validation.md"
        report.write_text("\n".join(validate(lake)) + "\n", encoding="utf-8")
        logger.info("wrote %s", report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
